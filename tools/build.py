#!/usr/bin/env python3
"""Rebuild assets/index.js: every unit's chapters, and which chapters link to which.

Run after adding or editing a unit:   python tools/build.py
Only the Python standard library is needed. The site works without running it, but new chapters then have
no link previews and no "Used in" chips until you do.
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
UNITS = ROOT / 'units'
SEC = re.compile(r'<section\b([^>]*\bclass="chapter(?: [^"]*)?"[^>]*)>(.*?)</section>', re.S)
ATTR = lambda name: re.compile(r'\b' + name + r'="([^"]*)"')
LINK = re.compile(r'<a\b[^>]*\bclass="x"[^>]*\bhref="\.\./([\w-]+)/(?:index\.html)?(?:#([\w-]+))?"', re.S)
LINK2 = re.compile(r'<a\b[^>]*\bhref="\.\./([\w-]+)/(?:index\.html)?(?:#([\w-]+))?"[^>]*\bclass="x"', re.S)
TAG = re.compile(r'<[^>]+>')

def text(html):
    return re.sub(r'\s+', ' ', TAG.sub('', html)).strip()

units, back = {}, {}
for page in sorted(UNITS.glob('*/index.html')):
    slug = page.parent.name
    if slug.startswith('_'):
        continue
    html = page.read_text(encoding='utf-8')
    title = re.search(r'<title>(.*?)</title>', html, re.S).group(1).split(' · ')[0].strip()
    chapters, stats = [], {'fx': html.count('class="fx"'), 'labs': html.count('class="lab"'), 'checks': 0}
    for attrs, body in SEC.findall(html):
        cid = (ATTR('id').search(attrs) or [None, None])[1]
        ctitle = (ATTR('data-title').search(attrs) or [None, None])[1]
        if not cid or not ctitle:
            continue
        is_ref = 'data-ref' in attrs
        summ = ATTR('data-summary').search(attrs)
        if summ:
            summary = summ.group(1)
        else:
            p = re.search(r'<p>(.*?)</p>', body, re.S)
            summary = text(p.group(1)) if p else ''
            summary = re.split(r'(?<=[.!?])\s', summary)[0][:180]
        if not is_ref:
            chapters.append({'id': cid, 'title': ctitle, 'summary': summary})
        targets = set()
        for s, i in LINK.findall(body) + LINK2.findall(body):
            targets.add((s, i or ''))
        builds = ATTR('data-builds').search(attrs)
        if builds:
            for ref in builds.group(1).split():
                s, _, i = ref.partition('#'); targets.add((s, i))
        for s, i in targets:
            if s == slug:
                continue
            key = s + ('#' + i if i else '')
            entry = [slug, cid, ctitle]
            if entry not in back.setdefault(key, []):
                back[key].append(entry)
        q = re.findall(r'<details class="check">.*?<script type="application/json">(.*?)</script>', body, re.S)
        for block in q:
            try: stats['checks'] += len(json.loads(block))
            except Exception as e: print('bad check json in', slug, cid, e)
    units[slug] = {'title': title, 'chapters': chapters, 'stats': stats}

# ---- images you add by name (see README, "Images"): picked up here so pages need no file probing.
#   naming in assets/img/README.txt: units/<slug>-tile|hero, paths/<path-id>, software/<id>
images = {'units': {}, 'paths': {}, 'software': {}}
IMG = ROOT / 'assets' / 'img'
for kind in images:
    folder = IMG / kind
    if not folder.exists():
        continue
    ORDER = ['.webp', '.avif', '.jpg', '.jpeg', '.png', '.svg']   # first wins when one name exists in several formats
    for f in sorted((f for f in folder.iterdir() if f.suffix.lower() in ORDER), key=lambda f: (f.stem, ORDER.index(f.suffix.lower()))):
        rel = 'assets/img/' + kind + '/' + f.name
        if kind == 'units':
            m = re.match(r'(.+)-(tile|hero)$', f.stem)
            if m:
                images['units'].setdefault(m.group(1), {}).setdefault(m.group(2), rel)
        else:
            images[kind].setdefault(f.stem, rel)

out = ROOT / 'assets' / 'index.js'
out.write_text('/* Generated by tools/build.py — do not edit by hand. */\nwindow.ATLAS_INDEX = ' +
               json.dumps({'units': units, 'backlinks': back, 'images': images}, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
missing = [k for k in back if k.split('#')[0] not in units or ('#' in k and k.split('#')[1] not in [c['id'] for c in units.get(k.split('#')[0], {}).get('chapters', [])])]
print(f"images: {sum(len(v) for v in images['units'].values())} unit, {len(images['paths'])} path, {len(images['software'])} software")
print(f'{len(units)} units, {sum(len(u["chapters"]) for u in units.values())} chapters, {sum(len(v) for v in back.values())} links')
if missing:
    print('Links to chapters that do not exist:', ', '.join(sorted(missing)))

# ---- cache busting: every page links its CSS and JS with ?v=<content hash>, so browsers and the
# service worker (sw.js) can keep files forever and still get new versions after a change.
import hashlib
_hash = {}
def _ver(path):
    if path not in _hash:
        _hash[path] = hashlib.sha1(path.read_bytes()).hexdigest()[:8] if path.exists() else None
    return _hash[path]
REF = re.compile(r'((?:src|href)=")([\w./-]+\.(?:css|js))(?:\?v=\w+)?(")')
pages = [ROOT / 'index.html', ROOT / 'impressum.html', ROOT / 'datenschutz.html'] + sorted(UNITS.glob('*/index.html'))
for page in pages:
    if not page.exists():
        continue
    html = page.read_text(encoding='utf-8')
    def sub(m):
        if m.group(2).startswith(('http:', 'https:', '//')):
            return m.group(0)
        v = _ver((page.parent / m.group(2)).resolve())
        return m.group(1) + m.group(2) + (f'?v={v}' if v else '') + m.group(3)
    new = REF.sub(sub, html)
    if new != html:
        page.write_text(new, encoding='utf-8')
print(f'versioned asset links in {len(pages)} pages')
